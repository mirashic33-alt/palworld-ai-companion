LINE_RE = re.compile(r"^\[(.*?)\]\s*(.*)$")

def ru_item(name):
    """Внутреннее имя предмета из лога -> человеческое, чтоб озвучка не читала латиницу.
    'Blueprint_FurArmor_3' -> 'чертёж брони', 'DogCoin' -> 'собачьи монеты'."""
    n = name.strip()
    if n.lower().startswith("blueprint"):
        rest = n.split("_", 1)[1] if "_" in n else ""
        rest = re.sub(r"_\d+$", "", rest)               # хвостовой уровень (_3) убираем
        low = rest.lower()
        if "armor" in low:   return "чертёж брони"
        if "weapon" in low or "gun" in low: return "чертёж оружия"
        if rest:             return "чертёж"
        return "чертёж"
    if n.lower() == "dogcoin":
        return "собачьи монеты"
    return n.replace("_", " ")                          # хоть без подчёркиваний


# Легендарные именные пассивки, которые мод иногда пишет сырым внутренним id — переводим,
# чтоб озвучка не читала латиницу И чтоб детектор ранга ниже их опознал как легендарные.
# (Обычно мод их сам переводит через passives_ru.lua, но если версия таблицы старая /
# кода нет в ней — прилетит латиницей, вот тут и подстрахуемся.)
RAW_LEGENDARY = {
    "Noukin": "Мускулистый",     # Musclehead (в таблице мода ОТСУТСТВУЕТ — лез латиницей)
    "Legend": "Легенда",         # Legend
    "Vampire": "Вампиризм",      # Vampiric (радужная)
    "Leech": "Вампиризм",        # Vampiric-вариант
}

# Типовые тиеровые пассивки, которые мод не перевёл (Deffence_up2_2, CraftSpeed_down1 …).
# Позитивные -> с римской цифрой уровня; НЕГАТИВНЫЕ -> без цифры, чтоб детектор ранга
# ниже не принял дебафф «_down2» за золотую пассивку II уровня.
_RAW_PASSIVE_RE = re.compile(r"\b(Attack|Deffence|Defence|CraftSpeed|MoveSpeed)_(up|down)(\d)(?:_\d+)?\b", re.I)
_RAW_UP   = {"attack": "Атака", "deffence": "Защита", "defence": "Защита",
             "craftspeed": "Работяга", "movespeed": "Скорость бега"}
_RAW_DOWN = {"attack": "Слабак", "deffence": "Хрупкий", "defence": "Хрупкий",
             "craftspeed": "Криворукий", "movespeed": "Медлительный"}
_ROMAN = {"1": "I", "2": "II", "3": "III"}

def _sub_raw_passive(m):
    base, direction, tier = m.group(1).lower(), m.group(2).lower(), m.group(3)
    if direction == "up":
        return f"{_RAW_UP.get(base, base)} {_ROMAN.get(tier, tier)}"
    return _RAW_DOWN.get(base, base)          # негативные — без римской цифры

# Голодные пассивки. Внимание: в КОДЕ игры Down/Up перевёрнуто относительно смысла —
# FullStomach_Down (в игре «Аскет») = сытость падает МЕДЛЕННЕЕ = ХОРОШАЯ пассивка;
# FullStomach_Up (в игре «Обжора») = голодает быстрее = дебафф. Старая версия мода
# переводила их наоборот («Быстрый/Медленный голод») — чиним обе формы здесь, чтоб
# и модель, и озвучка, и детектор ранга ниже видели правильные «Аскет»/«Обжора».
_HUNGER_RE = re.compile(r"PAL_FullStomach_(Up|Down)_(\d)", re.I)
def _sub_hunger_raw(m):
    name = "Обжора" if m.group(1).lower() == "up" else "Аскет"
    return f"{name} {_ROMAN.get(m.group(2), m.group(2))}"

# Рассудок (SAN) — тот же переворот Down/Up, что и у сытости:
# Sanity_Down = рассудок падает МЕДЛЕННЕЕ = ХОРОШАЯ пассивка («Трудоголик» — золотая);
# Sanity_Up   = падает быстрее = дебафф. Старая таблица мода звала их «Слабый/Крепкий
# рассудок» ровно наоборот — чиним и сырые коды, и старые переводы (мод в уже запущенной
# игре продолжает писать по-старому, пока игрок не перезайдёт).
_SANITY_DOWN = {"1": "Позитивное мышление", "2": "Трудоголик", "3": "Сердце непоколебимого короля"}
_SANITY_UP   = {"1": "Неустойчивый", "2": "Разрушительный", "3": "Разрушительный III"}
_SANITY_RE = re.compile(r"PAL_Sanity_(Up|Down)_(\d)", re.I)
def _sub_sanity_raw(m):
    table = _SANITY_UP if m.group(1).lower() == "up" else _SANITY_DOWN
    return table.get(m.group(2), m.group(0))

_SANITY_OLD_RE = re.compile(r"(Слабый|Крепкий) рассудок\s+(I{1,3})", re.I)
_ARAB = {"i": "1", "ii": "2", "iii": "3"}
def _sub_sanity_old(m):
    # «Слабый рассудок» шёл от Sanity_Down (на деле это плюс), «Крепкий» — от Sanity_Up (минус)
    table = _SANITY_DOWN if m.group(1).lower() == "слабый" else _SANITY_UP
    return table.get(_ARAB.get(m.group(2).lower(), ""), m.group(0))

def normalize(text):
    """Причёсывает строку события для модели/озвучки: имена предметов и пассивки."""
    m = re.match(r"(ПОЛУЧЕН ПРЕДМЕТ:\s*)(\S+)(.*)$", text)
    if m:
        return m.group(1) + ru_item(m.group(2)) + m.group(3)
    for raw, ru in RAW_LEGENDARY.items():
        text = text.replace(raw, ru)
    text = _RAW_PASSIVE_RE.sub(_sub_raw_passive, text)
    text = _HUNGER_RE.sub(_sub_hunger_raw, text)          # сырые FullStomach_Up/Down
    text = text.replace("Быстрый голод", "Аскет").replace("Медленный голод", "Обжора")
    text = _SANITY_RE.sub(_sub_sanity_raw, text)          # сырые Sanity_Up/Down
    text = _SANITY_OLD_RE.sub(_sub_sanity_old, text)      # старые «Слабый/Крепкий рассудок N»
    return text


# ------------------------------------------------------- ценность пассивок пала
# Легендарные (высший «золотой/радужный» ранг) — самые желанные пассивки. Ловим их
# В ЛЮБОЙ форме, в какой пассивка может долететь до нас:
#   • сырой внутренний код игры (Legend, Rare, Vampire, Leech, Noukin);
#   • наш перевод из RAW_LEGENDARY (Легенда, Мускулистый, Вампиризм);
#   • ОПИСАНИЕ, в которое разворачивает её мод — passives_ru.lua переводит именные
#     легендарки в описание БЕЗ римской цифры («Legend»→«Атака / Защита / HP»,
#     «Rare»(Lucky)→«Скорость работы / Атака / Слабый рассудок»). Раньше детектор
#     искал только римскую III / слово «легенда» и эти именные ПРОПУСКАЛ (tier 0).
# Русские подстроки и описания мода (сравниваем по нижнему регистру):
_LEGEND_RU = (
    "легенда",                                    # Legend (наш перевод + внутри описаний)
    "мускулист",                                  # Musclehead (Noukin)
    "кровожад", "ловкач", "владык", "свиреп",     # прочие именные высшего ранга
    "лёгкое тело", "легкое тело",                  # легендарная (игрок видел тултип 30.07 — WhiteDeer)
    "трудоголик",                                 # Workaholic (Sanity_Down_2) — золотая
    "сердце непоколебимого",                      # Sanity_Down_3 — высший ранг
    "атака / защита / hp",                        # мод-описание Legend
    "счастливчик",                                # мод-описание Lucky (Rare)
)
# Английские внутренние коды высшего ранга — по границе слова, чтоб не задеть чужие слова:
_LEGEND_CODE_RE = re.compile(r"\b(Legend|Rare|Vampire|Leech|Noukin)\b", re.I)
# Вампиризм: радужный Vampiric (Vampire/Leech) мод разворачивает в «Вампиризм» без цифры,
# LifeSteal_4/5 → «Вампиризм IV/V» — всё это высший ранг. «Вампиризм I/II/III» — обычный лайфстил.
_VAMP_HIGH_RE = re.compile(r"вампиризм(?!\s+I{1,3}\b)", re.I)

# НЕГАТИВНЫЕ пассивки-дебаффы. Их римская цифра — это НЕ «золото/легендарка», а сила ВРЕДА:
# «Обжора III» (код FullStomach_Up_3) = пал жрёт/голодает быстрее, чем выше — тем хуже.
# Их нельзя праздновать как удачу — на них Мия стебётся/сочувствует. Ловим по русским основам
# (уже нормализованы в normalize) + наши переводы сырых _down-кодов (Слабак/Хрупкий/Криворукий).
_BAD_STEMS = (
    "обжора",                 # FullStomach_Up — голодает быстрее (нормализовано из «Медленный голод»)
    "неустойчив", "разрушительн",      # Sanity_Up — рассудок падает быстрее
    "слабак", "хрупкий", "криворук",   # наши переводы raw Attack/Deffence/CraftSpeed _down
)

# Сырые непереведённые коды пассивок с АРАБСКИМ суффиксом уровня в хвосте
# (WorkSuitabilityAddRank_MonsterFarm_2, LifeSteal_4 …). Мод их не перевёл, а детектор
# выше искал только римские I/II/III — потому легендарки в таком виде МОЛЧАЛИ (был баг:
# Гринтэйл с «..._2» проходил как tier 0). Уровень читаем из хвостового «_N»; дебаффные
# коды (Down/Stamina/Sanity/Weak/Slow…) сюда НЕ берём, чтоб минус не праздновать как удачу.
_RAW_LVL_RE = re.compile(r"([A-Za-z][A-Za-z_]*?)_([2-5])\b")
_RAW_BAD_CODE = ("down", "stamina", "sanity", "weak", "slow", "decrease", "reduce", "debuff")

def _passives_str(text):
    """Из строки поимки вытаскивает подстроку с пассивками (между 'пассивки:' и 'приёмы:')."""
    m = re.search(r"пассивки:\s*(.*?)(?:,\s*приёмы:|\s*\])", text)
    return m.group(1).strip() if m else ""

def pal_name(text):
    """'ПОЙМАН ПАЛ: ★БОСС Фенглоуп [...]' -> 'Фенглоуп' (без метки босса)."""
    m = re.match(r"ПОЙМАН ПАЛ:\s*([^\[]+)", text)
    if not m:
        return ""
    return re.sub(r"^★?\s*БОСС\s*", "", m.group(1).strip()).strip()

def passive_tier(text):
    """Ценность пассивок пойманного пала — чем ярче пассивка, тем сильнее реакция Мии.
    Возвращает (level, note, kind):
      level: 0 — ничего особого; 2 — заметная; 3 — яркая (высший ранг).
      kind:  'good' — приятная находка (Мия радуется, чем выше — тем восторженнее);
             'bad'  — дебафф (Мия стебётся/сочувствует, чем выше — тем злее подъёб, НЕ радость).
    note — что подсветить Мие."""
    p = _passives_str(text)
    if not p:
        return 0, "", "good"
    low = p.lower()
    # НЕГАТИВНЫЕ первыми: «Обжора III» и т.п. — их римская III это сила ВРЕДА,
    # а не золото. Иначе детектор ниже принял бы дебафф за легендарную удачу (был баг).
    if any(s in low for s in _BAD_STEMS):
        if re.search(r"\b(III|IV|V)\b", p):
            return 3, p, "bad"
        if re.search(r"\bII\b", p):
            return 2, p, "bad"
        return 0, "", "good"          # дебафф I уровня — мелочь, не акцентируем
    # высший ранг (хорошее): именная легендарка, радужный вампиризм, уровень III/IV/V
    if (any(mk in low for mk in _LEGEND_RU)
            or _LEGEND_CODE_RE.search(p)
            or _VAMP_HIGH_RE.search(low)
            or re.search(r"\b(III|IV|V)\b", p)):
        return 3, p, "good"
    # сырые непереведённые коды с арабским уровнем (WorkSuitabilityAddRank_..._2, LifeSteal_4).
    # Мод не дал им римскую цифру — читаем уровень из хвоста «_N», дебаффные коды отсеяны.
    raw_lvls = [int(m2.group(2)) for m2 in _RAW_LVL_RE.finditer(p)
                if not any(b in m2.group(1).lower() for b in _RAW_BAD_CODE)]
    if raw_lvls:
        best = max(raw_lvls)
        if best >= 3:
            return 3, p, "good"
        if best == 2:
            return 2, p, "good"
    # золотые (второй уровень) + заметные именные без цифры (доп. прыжок, лайфстил I)
    if re.search(r"\bII\b", p) or "доп. прыжок" in low or "вампиризм" in low:
        return 2, p, "good"
    return 0, "", "good"


def legendary_passives(text):
    """Из строки события (поимка/покупка/вылупление) — список ИМЕННО легендарных
    пассивок высшего ранга, чтобы модель называла их вслух. Причина (игрок, 27.07):
    поймал Моззарину с Вампиризмом — детектор дал tier 3 и модель ликовала, но НЕ
    назвала вампира; ей говорили лишь «пассивка высшего ранга», без имени. Ловим ту
    же семью, что passive_tier: вампиризм (кроме I–III), Легенда, Мускулистый, III+."""
    p = _passives_str(text)
    if not p:
        return []
    out = []
    for token in (x.strip() for x in p.split(",")):
        low = token.lower()
        if not token or any(b in low for b in _BAD_STEMS):
            continue
        if (any(mk in low for mk in _LEGEND_RU)
                or _LEGEND_CODE_RE.search(token)
                or _VAMP_HIGH_RE.search(low)
                or re.search(r"\b(III|IV|V)\b", token)):
            out.append(token)
    return out


