def _log_api_error(kind: str, detail: str, manual: bool):
    """Пишет ошибки Gemini-запроса в файл — видно без консоли (.pyw)."""
    try:
        with open(_DEBUG_LOG, "a", encoding="utf-8") as f:
            f.write(f"[{time.strftime('%H:%M:%S')}] {'MANUAL' if manual else 'GAME'} {kind}: {detail}\n")
    except Exception:
        pass

