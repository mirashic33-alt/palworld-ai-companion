_CHAT_CACHE = {"mtime": 0.0, "lines": []}

def recent_oleg(n=5):
    """Последние N реплик игрока из chat.log — его слова, планы и указания.
    Раньше они жили ТОЛЬКО в потоке событий (10 строк) и вылетали за минуту игры:
    Мия «не слышала» того, что ей сказали пять минут назад. Кэш по mtime — файл
    читаем не на каждое событие, а только когда он изменился."""
    path = C.CHAT_LOG_FILE
    try:
        mt = os.path.getmtime(path)
    except OSError:
        return []
    if mt != _CHAT_CACHE["mtime"]:
        try:
            with open(path, "rb") as f:                  # только хвост: файл растёт вечно
                f.seek(0, os.SEEK_END)
                f.seek(max(0, f.tell() - 20000))
                txt = f.read().decode("utf-8", errors="ignore")
        except Exception:
            return []
        out = []
        for l in txt.splitlines():
            m = re.match(r"^\[.*?\]\s*игрок:\s*(.+)$", l)
            if m and m.group(1).strip():
                out.append(" ".join(m.group(1).split())[:200])
        _CHAT_CACHE["lines"], _CHAT_CACHE["mtime"] = out, mt
    return _CHAT_CACHE["lines"][-n:]


