def _squeeze_fact(system, payload, suffix=""):
    """Фоном: жмёт текст в строку факта и кладёт в базу знаний. Молча, ничего не ломает."""
    key = os.environ.get("GEMINI_API_KEY") or os.environ.get("GOOGLE_API_KEY")
    if not key:
        return
    body = {
        "systemInstruction": {"parts": [{"text": system}]},
        "contents": [{"parts": [{"text": payload}]}],
        "generationConfig": {"temperature": 0.2, "maxOutputTokens": 200,
                             "thinkingConfig": {"thinkingBudget": 0}},
    }
    try:
        r = requests.post(API_URL.format(model=getattr(C, "KNOWLEDGE_MODEL", "gemini-2.5-flash-lite")),
                          headers={"x-goog-api-key": key}, json=body, timeout=30)
        if r.status_code != 200:
            return
        parts = r.json().get("candidates", [{}])[0].get("content", {}).get("parts", [])
        fact = "".join(p.get("text", "") for p in parts).strip()
        if fact and "NONE" not in fact.upper():
            add_fact(fact.splitlines()[0].rstrip(". ") + suffix)
    except Exception:
        pass


