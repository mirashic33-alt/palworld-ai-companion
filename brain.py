def ask_gemini(event_block, state_summary, recent_replies, history="", game_map="", manual=False):
    key = os.environ.get("GEMINI_API_KEY") or os.environ.get("GOOGLE_API_KEY")
    if not key:
        return "(нет ключа GEMINI_API_KEY в окружении)"

    avoid = ""
    if recent_replies:
        avoid = ("\n\nТвои последние реплики (НЕ повторяй их, скажи иначе):\n- "
                 + "\n- ".join(recent_replies))

    gmap = f"Карта игры (общий фон, держи в голове, но НЕ пересказывай): {game_map}\n" if game_map else ""
    hist_label = "Что было до этого: " if manual else "Что было в игре до этого: "
    hist = f"{hist_label}{history}\n" if history else ""
    oleg = oleg_block()          # его слова живут дольше 10 событий — иначе он повторяет одно и то же
    words = getattr(C, "REPLY_WORDS", 18)

    if manual:
        # Прямое обращение игрока — не событие игры. Отвечать как в живом разговоре, длиннее.
        words = int(words * getattr(C, "MANUAL_WORDS_MULT", 2.5))
        user = (f"{gmap}"
                f"Контекст игры: {state_summary}.\n"
                f"{hist}{oleg}"
                f"игрок написал тебе напрямую (это НЕ событие игры, это живой разговор): {event_block}\n"
                f"Отвечай как подруга в разговоре — развёрнуто, живо, с юмором или иронией. "
                f"Уложись примерно в {words} слов.{avoid}")
    else:
        # Кульминация боя с боссом — вход в башню и финал (победа/поражение). Это редкие
        # эпичные моменты, их игрок просил по умолчанию развернуть вдвое против обычной реплики.
        if any(m in event_block for m in ("впереди бой", "ПОБЕДА НАД БОССОМ", "боссом ПРОИГРАН")):
            words = int(words * getattr(C, "BOSS_WORDS_MULT", 2.0))
        user = (f"{gmap}"
                f"Сейчас в игре: {state_summary}.\n"
                f"{hist}{oleg}"
                f"Только что произошло:\n{event_block}\n"
                f"Отреагируй живо и с юмором. Уложись примерно в {words} слов.{avoid}")

    gen_cfg = {
        "temperature": getattr(C, "TEMPERATURE", 1.15),
        # ВАЖНО: у Gemini 3 токены МЫШЛЕНИЯ считаются внутри maxOutputTokens.
        # На ручной ввод думалка включена (нужна для google_search) — поэтому даём
        # ЩЕДРЫЙ лимит, иначе thinking съедает бюджет и ответ рубится на 3 словах.
        "maxOutputTokens": 8192 if manual else max(60, words * 8),
    }
    if not manual:
        gen_cfg["thinkingConfig"] = {"thinkingBudget": 0}

    body = {
        "systemInstruction": {"parts": [{"text": _system_prompt()}]},
        "contents": [{"parts": [{"text": user}]}],
        "generationConfig": gen_cfg,
    }
    if manual:
        body["tools"] = [{"google_search": {}}]

    req_timeout = 90 if manual else 30   # search + thinking могут занять > 30 сек
    try:
        r = requests.post(API_URL.format(model=C.MODEL),
                          headers={"x-goog-api-key": key},
                          json=body, timeout=req_timeout)
        if r.status_code != 200:
            _log_api_error(f"HTTP {r.status_code}", r.text[:300], manual)
            return f"[ERR {r.status_code}]"
        cand = r.json().get("candidates", [{}])[0]
        parts = cand.get("content", {}).get("parts", [])
        # если ответ обрубился по лимиту токенов — залогируем, чтоб было видно причину
        if cand.get("finishReason") == "MAX_TOKENS":
            _log_api_error("MAX_TOKENS (ответ обрезан лимитом)", str(r.json().get("usageMetadata", ""))[:200], manual)
        # отфильтровываем thinking parts (thought=True) — они не для озвучки
        real_parts = [p for p in parts if not p.get("thought", False)]
        out = "".join(p.get("text", "") for p in real_parts).strip()
        if not out and parts:
            # все части были thought — берём как есть (лучше чем молчать)
            out = "".join(p.get("text", "") for p in parts).strip()
        if not out:
            _log_api_error("пустой ответ", str(r.json())[:300], manual)
            return "[ERR пусто]"
        # Ходила в интернет → фоном сожмём находку в строку факта и положим в базу знаний.
        # Строго ПОСЛЕ ответа и в своём потоке: озвучку не задерживает ни на миллисекунду.
        gm = cand.get("groundingMetadata") or {}
        if manual and (gm.get("groundingChunks") or gm.get("webSearchQueries")):
            import threading
            threading.Thread(target=_learn_from_search, args=(event_block, out),
                             daemon=True).start()
        # «Запиши себе в память» — раньше она отвечала «записала» и НЕ записывала:
        # механизма не было вовсе. Теперь его слова реально ложатся в знания.
        if manual and re.search(r"запо(м|мн)|запиш|запиши|заруб|не забыв|на будущее",
                                event_block, re.I):
            import threading
            threading.Thread(target=_learn_from_oleg, args=(event_block,), daemon=True).start()
        return out
    except Exception as e:
        _log_api_error("exception", str(e), manual)
        return f"[ERR {type(e).__name__}]"


