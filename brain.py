# --------------------------------------------- смерть игрока: схлопнуть в одну строку
# Одна гибель игрока прилетает до 4 строк из РАЗНЫХ каналов мода (серверный хук
# «ИГРОК УМЕР», клиентский kill-feed дважды, мультикаст) + мусор «сам себя убил»
# (Ari -> убил -> Ari) и болванка-убийца Player_Female/Male (класс персонажа, не
# реальный враг). Мия из-за этого называла трёх убийц за одну смерть (игрок, 31.07).
# Схлопываем всю пачку в ОДНУ строку «ИГРОК УМЕР[, убийца: X]» с настоящим убийцей.
_BOGUS_KILLERS = ("Player_Female", "Player_Male")
_FEED_VICTIM_RE = re.compile(r"->\s*убил\s*->\s*(.+?)\s*$")
_FEED_KILLER_RE = re.compile(r":\s*(.+?)\s*->\s*убил\s*->")
_NAMED_KILLER_RE = re.compile(r"убийца:\s*(.+?)\s*$")

def _is_self_kill(text):
    """«Ari -> убил -> Ari» — атакующий совпал с жертвой: мусор движка, всегда прочь."""
    v = _FEED_VICTIM_RE.search(text or "")
    k = _FEED_KILLER_RE.search(text or "")
    return bool(v and k) and v.group(1).strip() == k.group(1).strip()

def _is_player_death(text):
    """Строка о смерти самого игрока (игрока): «ИГРОК УМЕР…», «ПОГИБ НАВСЕГДА…»
    или kill-feed, где жертва — игрок («… -> убил -> Ari»)."""
    t = text or ""
    if "ИГРОК УМЕР" in t or "ПОГИБ НАВСЕГДА" in t:
        return True
    v = _FEED_VICTIM_RE.search(t)
    return bool(v) and v.group(1).strip().lower() == C.PLAYER_NAME.lower()

def _death_killer(text):
    """Настоящий убийца из строки смерти; '' если его нет или это болванка/сам игрок."""
    m = _NAMED_KILLER_RE.search(text or "") or _FEED_KILLER_RE.search(text or "")
    if not m:
        return ""
    k = m.group(1).strip()
    if not k or k in _BOGUS_KILLERS or k.lower() == C.PLAYER_NAME.lower():
        return ""
    return k

def collapse_deaths(texts):
    """Схлопывает пачку событий: самоубийства выкидывает, все строки смерти игрока
    заменяет ОДНОЙ «ИГРОК УМЕР[, убийца: X]» (настоящий убийца из любой строки пачки).
    Прочие события не трогает."""
    death_idx = [i for i, t in enumerate(texts)
                 if _is_player_death(t) and not _is_self_kill(t)]
    drop = {i for i, t in enumerate(texts) if _is_self_kill(t)}
    if not death_idx:
        return [t for i, t in enumerate(texts) if i not in drop]
    drop |= set(death_idx)
    killer = ""
    for i in death_idx:
        killer = _death_killer(texts[i])
        if killer:
            break
    hardcore = any("ПОГИБ НАВСЕГДА" in texts[i] for i in death_idx)
    head = ">> ИГРОК ПОГИБ НАВСЕГДА (хардкор)" if hardcore else ">> ИГРОК УМЕР"
    line = head + (", убийца: " + killer if killer else "")
    first = min(death_idx)
    out = []
    for i, t in enumerate(texts):
        if i == first:
            out.append(line)
        elif i not in drop:
            out.append(t)
    return out


# ------------------------------------------------- события-мусор чужого сервера
def ignore_event(text):
    """На что Мия НЕ реагирует вообще — не зовём модель, не озвучиваем (просьба
    игрока 25.07, чужой сервер): ТОЛЬКО серверная автоматика (списание монет,
    предел уровня, прогрессия, реклама). Чат чужих игроков НЕ глушим — его она
    комментирует и переводит игроку (см. промпт). На всё остальное — реагируем."""
    t = text or ""
    if "СИСТЕМА СЕРВЕРА" in t:   # весь серверный автомат: деньги, лимит уровня, объявления, реклама
        return True
    if "ЧУЖАЯ ПОИМКА" in t:      # сосед по серверу поймал пала рядом — это не наш улов
        return True
    # Телепортация игрока. Уточнено 03.08: перемещение ПО КАРТЕ (быстрое перемещение
    # через статую — редкое, осмысленное) игрок хочет отмечать, а глушить надо только
    # автоматический перенос после смерти на базу и возврат к палбоксу — он перебивал
    # реакцию на смерть. Lua-мод помечает перемещение по карте текстом «через статую
    # (быстрое перемещение)» — по нему и различаем. Вход/выход из башни глушится в самом
    # моде и сюда не доходит. ОТКРЫТИЕ НОВОЙ статуи («СТАТУЯ ТЕЛЕПОРТА») — тоже НЕ глушим.
    if "через статую" in t or "быстрое перемещение" in t:
        return False          # перемещение по карте — комментируем
    if "ТЕЛЕПОРТАЦИЯ" in t or "ТЕЛЕПОРТ завершён" in t:
        return True           # после смерти / к палбоксу / локальный варп — молчим
    return False


