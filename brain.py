# ------------------------------------------------------------- летописец
# Отдельная (дешёвая) работа: раз в N минут сжимает весь лог в короткую карту игры.
# Не реагирует, а строит контекст — уровень, палы, боссы, смерти, деньги. Реактивная
# Мия эту карту держит строкой в памяти и подмешивает к событиям.
CHRONICLE_PROMPT = (
    "Ты — летописец игровой сессии Palworld. Тебе дают сырой лог событий, разговоры "
    "игрока и уже известные вехи прошлых сессий. Ты не комментируешь и не шутишь — ты "
    "ведёшь две вещи:\n"
    "1) КАРТА — подробный снимок «где игрок СЕЙЧАС»: состояние, чем занят, к чему идёт. "
    "Пиши фактами, живо но без эмоций, конкретно.\n"
    "2) ВЕХИ — крупные необратимые вехи сессии (взяли важного босса, дошли до нового "
    "региона, сменили цель/проект, большое достижение), которых ЕЩЁ НЕТ в списке "
    "известных вех. Мелочь (рядовая поимка, +монеты, левелап на 1) вехой НЕ считается.\n"
    "Формат ответа СТРОГО такой, с этими двумя заголовками:\n"
    "=== КАРТА ===\n<12-18 коротких пунктов>\n=== ВЕХИ ===\n<новые вехи, каждая с новой "
    "строки через «- »; если новых нет — одно слово NONE>"
)

def _split_chronicle(out):
    """Разбирает ответ летописца на (карта, [новые вехи]). Если разметки нет —
    считаем весь текст картой, вех нет (не падаем на кривом ответе)."""
    parts = re.split(r"===\s*ВЕХИ\s*===", out, maxsplit=1, flags=re.I)
    game_map = re.sub(r"^\s*===\s*КАРТА\s*===\s*", "", parts[0], flags=re.I).strip()
    milestones = []
    if len(parts) > 1 and "NONE" not in parts[1].upper():
        for l in parts[1].splitlines():
            s = l.strip().lstrip("-•* ").strip()
            if len(s) >= 8:
                milestones.append(s)
    return game_map, milestones


def build_chronicle():
    """Читает весь events.log, сжимает в карту игры, пишет game_map.md, возвращает текст.
    Заодно дозаписывает новые вехи сессии в долгую память (game_memory.md).
    Возвращает '' если лога нет/пуст/нет ключа/ошибка — тогда токены не тратятся зря."""
    # Читаем только ХВОСТ лога, а не весь файл: в запрос всё равно уходит
    # последние CHRONICLE_MAX_CHARS символов, а файл может быть на десятки мегабайт.
    try:
        with open(C.LOG_FILE, "rb") as f:
            f.seek(0, os.SEEK_END)
            size = f.tell()
            back = C.CHRONICLE_MAX_CHARS * 4          # запас на UTF-8 (кириллица ~2 байта)
            f.seek(max(0, size - back))
            log = f.read().decode("utf-8", errors="ignore")
    except Exception:
        return ""
    if not log.strip():
        return ""
    key = os.environ.get("GEMINI_API_KEY") or os.environ.get("GOOGLE_API_KEY")
    if not key:
        return ""

    tail = log[-C.CHRONICLE_MAX_CHARS:]          # хвост, чтоб не раздувать запрос

    # читаем chat.log целиком (небольшой — не обрезаем, там видны цели игрока)
    chat = ""
    try:
        with open(C.CHAT_LOG_FILE, "r", encoding="utf-8", errors="ignore") as f:
            chat = f.read().strip()
    except Exception:
        pass

    chat_block = (f"\n\n=== РАЗГОВОРЫ ИГРОКА С АССИСТЕНТОМ (цели, намерения) ===\n{chat}" if chat else "")

    # долгая память: уже известные вехи — чтоб летописец не повторял их и достраивал арку
    known = load_long_memory()
    known_block = (f"\n\n=== УЖЕ ИЗВЕСТНЫЕ ВЕХИ (не повторяй их в ВЕХИ) ===\n{known}" if known else "")

    user = (
        "Вот источники о сессии Palworld.\n\n"
        "=== СОБЫТИЯ ИГРЫ (хвост лога) ===\n"
        + tail + chat_block + known_block + "\n\n"
        "Составь КАРТУ подробно (12-18 пунктов): примерный уровень; сколько разных палов "
        "поймано и кто чаще встречается; заметные/редкие палы и их пассивки; бои с боссами и "
        "их исход; сколько раз игрок погибал; сколько денег; на каком сервере/в каком мире "
        "(соло или чужой сервер, кто из игроков рядом); чем занят прямо сейчас; над чем "
        "работает (база, стройка, ферма, разведение); какова текущая цель или задача; что "
        "делал в прошлые заходы (из вех и разговоров), к чему идёт. Факты, конкретно, без "
        "эмоций. Если данных мало — так и скажи.\n"
        "Затем ВЕХИ: только крупные новые вехи, которых нет в известных. Нет — NONE."
    )
    body = {
        "systemInstruction": {"parts": [{"text": CHRONICLE_PROMPT}]},
        "contents": [{"parts": [{"text": user}]}],
        "generationConfig": {
            "temperature": 0.3,
            "maxOutputTokens": getattr(C, "CHRONICLE_MAX_TOKENS", 1200),
            "thinkingConfig": {"thinkingBudget": 0},
        },
    }
    try:
        r = requests.post(API_URL.format(model=C.CHRONICLE_MODEL),
                          headers={"x-goog-api-key": key},
                          json=body, timeout=40)
        if r.status_code != 200:
            return ""
        cand = r.json().get("candidates", [{}])[0]
        parts = cand.get("content", {}).get("parts", [])
        out = "".join(p.get("text", "") for p in parts).strip()
    except Exception:
        return ""
    if not out:
        return ""
    game_map, milestones = _split_chronicle(out)
    if milestones:                       # новые вехи — в долгую память (дозапись)
        append_milestones(milestones)
    if game_map:
        try:
            with open(C.CHRONICLE_FILE, "w", encoding="utf-8") as f:
                f.write("# Карта игры (пишет летописец, обновляется на лету)\n"
                        f"# {time.strftime('%Y-%m-%d %H:%M:%S')}\n\n" + game_map + "\n")
        except Exception:
            pass
    return game_map


# ------------------------------------------------------- долгая память (вехи)
# Копится ДОЗАПИСЬЮ (в отличие от карты, что затирается). Летописец раз в 15 минут
# дописывает сюда новые вехи сессии; старые не трогает. Дедуп по теме, чтоб одна и та
# же веха не легла дважды разными словами. В быстрые реакции не подмешивается — питает
# летописца, а он через карту питает реакции (скорость озвучки не страдает).
def load_long_memory():
    """Текст долгой памяти ('' если файла нет). Отдаём целиком — он небольшой."""
    try:
        with open(C.MEMORY_LONG_FILE, "r", encoding="utf-8") as f:
            return "\n".join(l.rstrip() for l in f
                             if l.strip() and not l.lstrip().startswith("#")).strip()
    except Exception:
        return ""


def append_milestones(lines):
    """Дозаписывает новые вехи в game_memory.md. Дубли по теме (_fact_key) не пишем."""
    try:
        try:
            with open(C.MEMORY_LONG_FILE, "r", encoding="utf-8") as f:
                have = {_fact_key(l) for l in f if l.strip() and not l.lstrip().startswith("#")}
        except OSError:
            have = set()
            with open(C.MEMORY_LONG_FILE, "w", encoding="utf-8") as f:
                f.write("# Долгая память: вехи сессий (дозапись, чистит игрок руками)\n\n")
        with open(C.MEMORY_LONG_FILE, "a", encoding="utf-8") as f:
            for s in lines:
                s = " ".join(s.split()).strip(" -")
                if len(s) >= 8 and _fact_key(s) not in have:
                    f.write(f"- [{time.strftime('%m-%d %H:%M')}] {s}\n")
                    have.add(_fact_key(s))
    except Exception as e:
        _log_api_error("MEMORY_LONG write", str(e), False)

