# ------------------------------------------------------------- база знаний по игре
# Копится сама: когда Мия на ручной вопрос сходила в интернет, находка фоном жмётся
# в одну строку и падает в знания.md. Файл отдаём модели ЦЕЛИКОМ (он крошечный) —
# никакого поиска по нему, искать дороже, чем скормить всё разом.
_KN_CACHE = {"mtime": 0.0, "text": ""}

def load_knowledge():
    """Текст базы знаний. Кэш по времени правки — на диск лезем, только если файл менялся."""
    path = getattr(C, "KNOWLEDGE_FILE", "")
    if not path:
        return ""
    try:
        mt = os.path.getmtime(path)
    except OSError:
        return ""
    if mt != _KN_CACHE["mtime"]:
        try:
            with open(path, "r", encoding="utf-8") as f:   # шапку-комментарий в промпт не тащим
                _KN_CACHE["text"] = "\n".join(
                    l.rstrip() for l in f if l.strip() and not l.lstrip().startswith("#")).strip()
            _KN_CACHE["mtime"] = mt
        except Exception:
            return ""
    return _KN_CACHE["text"]


def _fact_key(line):
    """Ключ для дедупа: тема факта — то, что до двоеточия, иначе первые три слова."""
    body = line.lstrip("- ").strip()
    # снять таймстамп «[MM-DD HH:MM] » в начале вехи — иначе ключом станет ДАТА (двоеточие
    # времени), у старых строк файла и новых вех ключи не совпадут и дедуп не сработает
    body = re.sub(r"^\[[^\]]*\]\s*", "", body)
    head = body.split(":", 1)[0] if ":" in body[:60] else " ".join(body.split()[:3])
    return re.sub(r"[^\w]+", "", head.lower())


def add_fact(line):
    """Кладёт факт в знания.md. Новая тема — дописываем в конец, знакомая — ОБНОВЛЯЕМ
    её строку свежими данными. Лимита нет; остальные строки и комментарии игрока
    остаются как есть — правится ровно одна строка."""
    line = " ".join((line or "").split()).strip(" -")
    if len(line) < 8:
        return
    path = C.KNOWLEDGE_FILE
    try:
        try:
            with open(path, "r", encoding="utf-8") as f:
                raw = f.readlines()
        except OSError:
            raw = []
        key = _fact_key(line)
        for i, l in enumerate(raw):
            s = l.strip()
            if not s or s.startswith("#") or _fact_key(s) != key:
                continue
            if s == "- " + line:        # то же самое — файл не трогаем
                return
            raw[i] = "- " + line + "\n"
            with open(path, "w", encoding="utf-8") as f:
                f.writelines(raw)
            _KN_CACHE["mtime"] = 0.0
            return
        with open(path, "a", encoding="utf-8") as f:
            f.write("- " + line + "\n")
        _KN_CACHE["mtime"] = 0.0     # заставим перечитать
    except Exception as e:
        _log_api_error("KNOWLEDGE write", str(e), True)


