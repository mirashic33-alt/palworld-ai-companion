# приоритет: 3 рефлекс (важны мс), 2 событие, 1 болтовня (спам-класс)
def classify(text):
    t = text.lower()
    if ("низкое hp" in t or "пал слёг" in t or "пал слег" in t or "убил игрока" in t
            or "игрок умер" in t or "умер" in t or "погиб" in t):
        return "reflex", 3
    if any(k in text for k in ("ПОЙМАН ПАЛ", "ВЫЛУПИЛСЯ", "КУПИЛ ПАЛА", "НАЙДЕНО ЯЙЦО",
                               "ЯЙЦО (простое)",
                               "ЛЕВЕЛАП", "ОТКРЫТ СУНДУК", "МЕТАЛЛОЛОМ", "ТАЙНИК", "ЗАПИСКА", "КЛЕТК", "ГРУЗ ПОДДЕРЖКИ", "ЗАХОД В МИР", "ПОДЗЕМЕЛЬЕ", "БОСС", "boss",
                               "ПАЛ УБИТ", "ТОРГОВЕЦ", "ПОЛУЧЕН ПРЕДМЕТ", "РАЗГОВОР С",
                               "ЭФФИГ", "СТАТУЯ", "ФРУКТ", "ОЧКИ", "ЧАТ ИГРОКА", "СИСТЕМА СЕРВЕРА",
                               "ЭКСПЕДИЦ",
                               "ТЕЛЕПОРТ",
                               "УБИЙСТВО (сервер)", "СМЕРТЬ (сервер)", "хардкор",
                               "РЕЙД", "РЕЙДЕР", "НА БАЗЕ")):
        return "event", 2
    return "chatter", 1


# ------------------------------------------------------------- модель мира
class WorldState:
    """Держит «сейчас»: события обновляют состояние, а не летят в модель по одному."""
    def __init__(self):
        self.last_pal = None
        self.money = None
        self.level = None
        self.recent = []   # последние N коротких описаний

    def update(self, text):
        m = re.match(r"ПОЙМАН ПАЛ:\s*([^\[]+)", text)
        if m:
            self.last_pal = m.group(1).strip()
        m = re.search(r"стало\s+(\d+)", text)
        if m:
            self.money = int(m.group(1))
        m = re.search(r"ЛЕВЕЛАП.*?уровень\s+(\d+)", text)   # запоминаем текущий уровень игрока
        if m:
            self.level = int(m.group(1))
        self.recent.append(text)
        self.recent = self.recent[-C.RECENT_EVENTS:]

    def summary(self):
        parts = []
        if self.level is not None:
            parts.append(f"уровень игрока: {self.level}")
        if self.last_pal:
            parts.append(f"последний пойманный пал: {self.last_pal}")
        if self.money is not None:
            parts.append(f"денег: {self.money}")
        return "; ".join(parts) if parts else "начало сессии"

    def history(self, exclude=0):
        """Выжимка того, что было в игре ДО текущего события — для контекста.
        exclude — сколько свежих строк отрезать с хвоста (это уже само «сейчас»)."""
        past = self.recent[:-exclude] if exclude else self.recent
        return "; ".join(past[-C.RECENT_EVENTS:]) if past else ""


# ------------------------------------------------------------- диспетчер
class Dispatcher:
    """Фильтрует поток: душит спам-класс по кулдауну, выкидывает протухшее."""
    def __init__(self):
        self._last_chatter = 0.0

    def keep(self, text):
        cat, prio = classify(text)
        now = time.monotonic()
        if cat == "chatter":
            if now - self._last_chatter < C.CHATTER_COOLDOWN_SEC:
                return False          # мелочь уже недавно комментировали — молчим
            self._last_chatter = now
        return True


